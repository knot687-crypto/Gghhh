// Writes the generated Luau data modules consumed by the Roblox runtime:
//   src/ReplicatedStorage/AAAMotion/Generated/{Clips/<Name>.luau, Rig, Tuning, VFXRecipes, Layout, Weapon}
// Run: node anim/export-luau.mjs   (after editing clips/tuning/vfx data)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from './build.mjs';
import { EASE_NAMES } from './core/easing.mjs';
import { R15, VM } from './core/rig.mjs';
import { LAYOUT } from './layout.mjs';
import { ATTACKS, DEFENSE, MOVE } from './tuning.mjs';
import { COLORS, EFFECTS, PARTICLES, RIBBON, SHAKES } from './vfx.mjs';
import { KATANA, KATANA_POINTS, VM_WEAPON_SCALE } from './weapon.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const outDir = path.join(root, 'src/ReplicatedStorage/AAAMotion/Generated');

const HEADER = '-- AUTO-GENERATED by tools/anim/export-luau.mjs. Do not edit by hand; edit the tools/anim sources.\n';

function num(x, dp = 4) {
  if (Number.isInteger(x)) return String(x);
  let s = x.toFixed(dp);
  s = s.replace(/0+$/, '').replace(/\.$/, '');
  if (s === '-0') s = '0';
  return s;
}

const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/;
function key(k) {
  return IDENT.test(k) ? k : `[${JSON.stringify(k)}]`;
}

// Generic JSON -> Luau literal.
export function lua(v, indent = '', opts = {}) {
  const dp = opts.dp ?? 4;
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'number') return num(v, dp);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'string') return JSON.stringify(v);
  if (Array.isArray(v)) {
    if (v.every((x) => typeof x === 'number')) return `{ ${v.map((x) => num(x, dp)).join(', ')} }`;
    if (v.length === 0) return '{}';
    const inner = indent + '\t';
    return `{\n${v.map((x) => inner + lua(x, inner, opts)).join(',\n')},\n${indent}}`;
  }
  const entries = Object.entries(v).filter(([, x]) => x !== undefined);
  if (entries.length === 0) return '{}';
  const inner = indent + '\t';
  return `{\n${entries.map(([k, x]) => `${inner}${key(k)} = ${lua(x, inner, opts)}`).join(',\n')},\n${indent}}`;
}

function channel(ch) {
  const out = { t: ch.t.map((x) => +x.toFixed(4)), v: ch.v.map((x) => +x.toFixed(4)), m: ch.m.map((x) => +x.toFixed(3)) };
  if (ch.e.some((e) => e !== 0)) out.e = ch.e;
  return out;
}

function clipModule(c) {
  const tracks = {};
  for (const [joint, chans] of Object.entries(c.tracks)) {
    tracks[joint] = {};
    for (const [name, ch] of Object.entries(chans)) tracks[joint][name] = channel(ch);
  }
  const data = {
    name: c.name,
    rig: c.rig,
    length: c.length,
    loop: c.loop,
    additive: c.additive,
    group: c.group,
    tracks,
    markers: c.markers,
    meta: c.meta,
    swings: c.swings
      ? c.swings.map((s) => ({ ...s, points: s.points.map((p) => ({ t: p.t, base: p.base, tip: p.tip })) }))
      : undefined,
  };
  return `${HEADER}-- Clip: ${c.name} (${c.rig}, ${c.length.toFixed(3)}s${c.loop ? ', loop' : ''})\nreturn ${lua(data)}\n`;
}

function write(rel, text) {
  const file = path.join(outDir, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

export async function exportLuau() {
  const clips = await build();
  fs.rmSync(path.join(outDir, 'Clips'), { recursive: true, force: true });
  for (const c of Object.values(clips)) write(`Clips/${c.name}.luau`, clipModule(c));
  write(
    'Clips/init.luau',
    `${HEADER}-- Lazily requires every clip module in this folder: Clips.Run, Clips.Light1, ...\n` +
      `local folder = script\nlocal cache = {}\nreturn setmetatable({}, {\n\t__index = function(_, name)\n\t\tlocal v = cache[name]\n\t\tif v == nil then\n\t\t\tlocal m = folder:FindFirstChild(name)\n\t\t\tif not m then\n\t\t\t\treturn nil\n\t\t\tend\n\t\t\tv = require(m)\n\t\t\tcache[name] = v\n\t\tend\n\t\treturn v\n\tend,\n})\n`,
  );
  const rigData = (rig) => ({
    name: rig.name,
    root: rig.root,
    parts: rig.parts,
    joints: rig.joints.map((j) => ({ name: j.name, part0: j.part0, part1: j.part1, c0: j.c0, c0r: j.c0r, c1: j.c1 })),
    sheath: rig.sheath,
    ground: rig.ground,
    hipHeight: rig.hipHeight,
    virtualJoints: rig.virtualJoints,
  });
  write('Rig.luau', `${HEADER}return ${lua({ R15: rigData(R15), VM: rigData(VM), EaseNames: EASE_NAMES })}\n`);
  write('Tuning.luau', `${HEADER}return ${lua({ MOVE, ATTACKS, DEFENSE })}\n`);
  write('VFXRecipes.luau', `${HEADER}return ${lua({ COLORS, PARTICLES, EFFECTS, RIBBON, SHAKES })}\n`);
  write('Layout.luau', `${HEADER}return ${lua(LAYOUT)}\n`);
  write('Weapon.luau', `${HEADER}return ${lua({ KATANA, POINTS: KATANA_POINTS, VM_SCALE: VM_WEAPON_SCALE })}\n`);
  return clips;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const clips = await exportLuau();
  const size = fs
    .readdirSync(path.join(outDir, 'Clips'))
    .reduce((s, f) => s + fs.statSync(path.join(outDir, 'Clips', f)).size, 0);
  console.log(`exported ${Object.keys(clips).length} clips (${(size / 1024).toFixed(0)} KB) -> ${path.relative(root, outDir)}`);
}
